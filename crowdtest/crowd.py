"""Crowd mode: hundreds of simulated people react to your site, cheaply or for free.

Real browsing is expensive per person, so crowd mode splits the work (the method large agent simulations use):
  1. a plain crawler reads the site's pages once (no AI, no cost);
  2. people are generated by mixing traits (age, job, country, device, tech comfort, patience, attitude), no AI needed;
  3. each person makes ONE short model call: read the captured pages, react to the goal.
The pages are the same for everyone, so with Claude they are cached and each extra person costs almost nothing; with a
local model (Ollama, LM Studio) it costs nothing at all and needs no account or key.
What it cannot see: clicks that fail, layout bugs and broken flows. Use the browsing visitors for those.
"""
from __future__ import annotations

import asyncio
import json
import os
import random
import re
import threading
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict, dataclass
from html.parser import HTMLParser
from urllib.parse import urldefrag, urljoin, urlparse

import requests

UA = "crowdtest/0.2 (page reader for usability simulation)"


# ---------------------------------------------------------------- 1. read the site
class _Text(HTMLParser):
    SKIP = {"script", "style", "noscript", "svg", "template"}

    def __init__(self):
        super().__init__()
        self.parts, self.links, self.title, self._skip, self._in_title = [], [], "", 0, False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in self.SKIP:
            self._skip += 1
        if tag == "title":
            self._in_title = True
        if tag == "a" and a.get("href"):
            self.links.append(a["href"])
        if tag in ("button", "input") and (a.get("value") or a.get("placeholder") or a.get("aria-label")):
            self.parts.append(f"[{tag}: {a.get('value') or a.get('placeholder') or a.get('aria-label')}]")
        if tag in ("h1", "h2", "h3", "li", "p", "br", "tr"):
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in self.SKIP and self._skip:
            self._skip -= 1
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data.strip()
        elif not self._skip and data.strip():
            self.parts.append(data.strip())


def crawl(url: str, max_pages: int = 8, max_chars: int = 6000) -> list[dict]:
    """Same-site pages reachable from the start page (breadth first), as visible text. Plain HTTP: pages that build their
    content with JavaScript only show what the server sends."""
    host = urlparse(url).hostname
    queue, seen, pages = [url], set(), []
    while queue and len(pages) < max_pages:
        u = urldefrag(queue.pop(0))[0]
        if urlparse(u).path == "":
            u += "/"                                   # example.com and example.com/ are the same page
        if u in seen or urlparse(u).hostname != host:
            continue
        seen.add(u)
        try:
            r = requests.get(u, headers={"User-Agent": UA}, timeout=15)
        except requests.RequestException:
            continue
        if r.status_code >= 400 or "html" not in r.headers.get("content-type", ""):
            continue
        p = _Text()
        p.feed(r.text)
        text = re.sub(r"\n\s*\n+", "\n", " ".join(p.parts)).strip()
        pages.append({"url": u, "title": p.title[:120], "text": text[:max_chars]})
        queue += [urljoin(u, h) for h in p.links if not h.startswith(("mailto:", "tel:", "javascript:"))]
    return pages


# ---------------------------------------------------------------- 2. generate people
TRAITS = {
    "age": ["19", "24", "31", "38", "45", "52", "60", "68", "75"],
    "job": ["student", "nurse", "small-business owner", "software engineer", "teacher", "retail worker", "farmer",
            "accountant", "freelance designer", "operations manager", "retired", "tradesperson", "marketing coordinator"],
    "country": ["Australia", "United States", "India", "United Kingdom", "Kenya", "Brazil", "Germany", "Philippines", "Canada", "Nigeria"],
    "device": ["phone", "phone", "laptop", "tablet"],
    "tech": ["low", "medium", "medium", "high"],
    "patience": ["impatient", "average", "patient"],
    "attitude": ["sceptical", "neutral", "curious", "in a hurry", "price-sensitive", "privacy-conscious"],
    "english": ["first language", "first language", "second language, fluent", "basic"],
}


@dataclass
class Person:
    id: int
    age: str
    job: str
    country: str
    device: str
    tech: str
    patience: str
    attitude: str
    english: str

    audience: str = ""

    def describe(self) -> str:
        who = f"{self.audience} ({self.job} background)" if self.audience else self.job
        return (f"You are a {self.age}-year-old {who} in {self.country}, on a {self.device}. Tech comfort: {self.tech}. "
                f"You are {self.patience} and {self.attitude}. English: {self.english}.")


def people(n: int, seed: int = 7, audience: str = "") -> list[Person]:
    """audience (optional): who the site is for, e.g. "farmer or farm adviser"; without it the crowd is the general public."""
    rng = random.Random(seed)
    return [Person(i, *(rng.choice(TRAITS[k]) for k in TRAITS), audience=audience) for i in range(n)]


# ---------------------------------------------------------------- 3. one reaction per person
SYSTEM = """You simulate one specific person reading a website, to find usability problems before real users do.
React honestly as that person would: their patience, tech comfort, English level and attitude change what they notice,
understand and trust. Judge only from the page text given; you cannot click. Reply with JSON only, exactly:
{"would_complete": "yes" | "maybe" | "no", "confusing": ["..."], "missing": ["..."], "trust_concerns": ["..."],
 "would_return": "yes" | "maybe" | "no", "quote": "one sentence in this person's own voice"}
Keep each list to at most 3 short items, naming the page or element."""


def site_block(url: str, goal: str, pages: list[dict]) -> str:
    body = "\n\n".join(f"=== PAGE {i + 1}: {p['title'] or p['url']} ({p['url']}) ===\n{p['text']}" for i, p in enumerate(pages))
    return f"Website: {url}\nThe visitor's goal: {goal}\n\n{body}"


def _parse(text: str) -> dict | None:
    try:
        d = json.loads(text[text.index("{"): text.rindex("}") + 1])
        return {k: d.get(k) for k in ("would_complete", "confusing", "missing", "trust_concerns", "would_return", "quote")}
    except (ValueError, AttributeError):
        return None


class Backend:
    """anthropic: Claude via the official SDK, the shared pages cached so each person costs little.
    ollama / openai: a local server (Ollama, LM Studio, llama.cpp, vLLM), free, no key."""

    def __init__(self, provider: str = "ollama", model: str | None = None, base_url: str | None = None):
        self.provider = provider
        self.model = model or {"anthropic": "claude-haiku-5-5", "ollama": "qwen3:8b"}.get(provider, "local-model")
        self.base_url = (base_url or {"ollama": "http://localhost:11434"}.get(provider, "")).rstrip("/")
        self.tokens = {"in": 0, "out": 0, "cache_read": 0, "cache_write": 0}
        self._lock = threading.Lock()
        if provider == "anthropic":
            import anthropic
            self.client = anthropic.Anthropic()

    def chat(self, system: str, shared: str, user: str, max_tokens: int = 1200) -> str:
        """One call. `shared` is the part that is identical for every person (cached on Claude)."""
        if self.provider == "anthropic":
            # short structured replies: no thinking step (allowed at low effort), so the answer is not cut off by the cap
            r = self.client.messages.create(
                model=self.model, max_tokens=max_tokens, output_config={"effort": "low"}, thinking={"type": "disabled"},
                system=[{"type": "text", "text": system}, {"type": "text", "text": shared or "-", "cache_control": {"type": "ephemeral"}}],
                messages=[{"role": "user", "content": user}])
            u = r.usage
            with self._lock:
                self.tokens["in"] += u.input_tokens; self.tokens["out"] += u.output_tokens
                self.tokens["cache_read"] += u.cache_read_input_tokens or 0; self.tokens["cache_write"] += u.cache_creation_input_tokens or 0
            return next((b.text for b in r.content if b.type == "text"), "")
        msgs = [{"role": "system", "content": system + "\n\n" + shared}, {"role": "user", "content": user}]
        if self.provider == "ollama":
            r = requests.post(f"{self.base_url}/api/chat", timeout=600, json={
                "model": self.model, "stream": False, "format": "json", "options": {"num_ctx": 16384}, "messages": msgs})
            r.raise_for_status()
            d = r.json()
            with self._lock:
                self.tokens["in"] += d.get("prompt_eval_count", 0); self.tokens["out"] += d.get("eval_count", 0)
            return d["message"]["content"]
        r = requests.post(f"{self.base_url}/chat/completions", timeout=600, headers={"Authorization": f"Bearer {os.environ.get('OPENAI_API_KEY', 'local')}"},
                          json={"model": self.model, "messages": msgs, "max_tokens": max_tokens})
        r.raise_for_status()
        return r.json()["choices"][0]["message"]["content"]

    def react(self, site: str, person: Person) -> dict | None:
        return _parse(self.chat(SYSTEM, site, f"{person.describe()}\nRead the website above and react to the goal."))

    def cost_usd(self) -> float:
        if self.provider != "anthropic":
            return 0.0
        from crowdtest.run import PRICE_PER_M
        pin, pout = PRICE_PER_M.get(self.model, (0.10, 0.50))
        t = self.tokens                                    # cache reads bill at a tenth of input, writes at 1.25x
        return round((t["in"] * pin + t["cache_read"] * pin * 0.1 + t["cache_write"] * pin * 1.25 + t["out"] * pout) / 1e6, 4)


def run_crowd(url: str, goal: str, n: int, backend: Backend, pages: list[dict], workers: int = 4, progress: dict | None = None,
              audience: str = "") -> list[dict]:
    site = site_block(url, goal, pages)
    crowd = people(n, audience=audience)
    lock = threading.Lock()
    if progress is not None:
        progress.update(total=n, done=0, failed=0)

    def one(p: Person) -> dict:
        try:
            r = backend.react(site, p)
        except Exception as e:                            # one failed call must not sink the crowd
            r, err = None, f"{type(e).__name__}"
        else:
            err = None if r else "unreadable reply"
        if progress is not None:
            with lock:
                progress["done"] += 1
                progress["failed"] += r is None
        return {"person": asdict(p), "reaction": r, "error": err}

    with ThreadPoolExecutor(max_workers=workers) as ex:
        return list(ex.map(one, crowd))


# ---------------------------------------------------------------- 4. sum it up
def summarise(results: list[dict]) -> dict:
    from collections import Counter, defaultdict
    ok = [r for r in results if r["reaction"]]
    rate = lambda rows, key, val: round(100 * sum((x["reaction"].get(key) or "").lower() == val for x in rows) / len(rows)) if rows else 0
    groups = {}
    for trait in ("device", "tech", "age", "english", "attitude"):
        by = defaultdict(list)
        for r in ok:
            by[r["person"][trait]].append(r)
        groups[trait] = {k: {"people": len(v), "would_complete_pct": rate(v, "would_complete", "yes")} for k, v in sorted(by.items())}
    count = lambda key: Counter(i.strip().rstrip(".").lower() for r in ok for i in (r["reaction"].get(key) or [])[:3] if isinstance(i, str) and i.strip())
    return {"people": len(results), "answered": len(ok), "would_complete_pct": rate(ok, "would_complete", "yes"),
            "maybe_pct": rate(ok, "would_complete", "maybe"), "would_return_pct": rate(ok, "would_return", "yes"),
            "top_confusing": count("confusing").most_common(10), "top_missing": count("missing").most_common(10),
            "top_trust": count("trust_concerns").most_common(10), "groups": groups,
            "top_confusing_all": count("confusing").most_common(150), "top_missing_all": count("missing").most_common(150),
            "top_trust_all": count("trust_concerns").most_common(100),
            "quotes": [(r["person"], r["reaction"]["quote"]) for r in ok[:12] if r["reaction"].get("quote")]}


GROUP_PROMPT = """You are a UX researcher. Below are short complaints from many simulated visitors to one website, one per
line, with how many people wrote each exact line. Merge lines that describe the same problem. Reply with JSON only:
{"issues": [{"title": "short name of the problem", "mentions": <total count across merged lines>, "fix": "one concrete fix"}]}
At most 8 issues, most mentions first."""


def group_issues(backend: Backend, s: dict) -> list[dict]:
    """One extra call to merge differently worded complaints; falls back to the exact counts."""
    lines = [f"{n}x {t}" for t, n in (s["top_confusing_all"] + s["top_missing_all"] + s["top_trust_all"])][:400]
    if not lines:
        return []
    try:
        text = backend.chat(GROUP_PROMPT, "", "\n".join(lines), max_tokens=1500)
        return json.loads(text[text.index("{"): text.rindex("}") + 1])["issues"][:8]
    except Exception:
        return [{"title": t, "mentions": n, "fix": ""} for t, n in s["top_confusing"][:8]]
